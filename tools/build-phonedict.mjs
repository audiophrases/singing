/*
 * Builds js/lyrics/phonedict.js: the robot singer's pronunciation dictionary.
 * A one-off generator, not part of the app. Run it again after adding songs
 * with unusual words:
 *
 *   node tools/build-phonedict.mjs <cmudict.dict> <count_1w.txt> [words]
 *
 *   cmudict.dict  https://github.com/cmusphinx/cmudict (BSD licence)
 *   count_1w.txt  https://norvig.com/ngrams/ (word frequencies, only used to
 *                 choose which CMUdict words to keep)
 *   words         how many of the most frequent words to keep (default 16000)
 *
 * Every word in the songs and word lists is kept too. Phones are stored one
 * character each (see CODES in js/lyrics/phonemes.js), without stress marks.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARPA } from '../js/lyrics/phonemes.js';

const [dictPath, freqPath, wantArg] = process.argv.slice(2);
if (!dictPath || !freqPath) {
  console.error('Usage: node tools/build-phonedict.mjs <cmudict.dict> <count_1w.txt> [words]');
  process.exit(1);
}
const want = Number(wantArg) || 16000;
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

const cmu = new Map();
for (const line of fs.readFileSync(dictPath, 'utf8').split('\n')) {
  const m = /^([a-z'.-]+)(\(\d+\))?\s+([^#]+)/.exec(line.trim());
  if (!m || m[2]) continue; // first pronunciation only
  const code = m[3].trim().split(/\s+/).map((p) => ARPA[p.replace(/\d/, '')]).join('');
  if (!code.includes('undefined')) cmu.set(m[1], code);
}

const keep = new Set();
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (p.endsWith('.js')) {
      for (const w of fs.readFileSync(p, 'utf8').toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g) || []) keep.add(w);
    }
  }
}
walk(path.join(root, 'js', 'data'));
walk(path.join(root, 'js', 'lyrics'));
walk(path.join(root, 'js', 'views'));

let n = 0;
for (const line of fs.readFileSync(freqPath, 'utf8').split('\n')) {
  const w = line.split('\t')[0];
  if (!w || !cmu.has(w)) continue;
  keep.add(w);
  if (++n >= want) break;
}

const rows = [...keep].filter((w) => cmu.has(w)).sort().map((w) => `${w} ${cmu.get(w)}`);
const licencePath = path.join(path.dirname(dictPath), 'LICENSE');
const licence = fs.existsSync(licencePath) ? fs.readFileSync(licencePath, 'utf8').trim() : '';
if (!licence) {
  console.error(`Put CMUdict's LICENSE file next to ${dictPath}: its notice must ship with the data.`);
  process.exit(1);
}
const notice = licence.split(/\r?\n/).map((l) => ` * ${l}`.trimEnd()).join('\n');
const out = `/*
 * Pronunciations for the robot singer, generated by tools/build-phonedict.mjs
 * from the CMU Pronouncing Dictionary. Do not edit by hand.
 *
${notice}
 */
export const PHONE_DICT = \`
${rows.join('\n')}
\`;
`;
const dest = path.join(root, 'js', 'lyrics', 'phonedict.js');
fs.writeFileSync(dest, out);
console.log(`${rows.length} words, ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB -> ${path.relative(root, dest)}`);
