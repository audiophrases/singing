/*
 * Builds js/lyrics/stressdict.js: which vowel carries the word stress, for
 * the words of the pronunciation dictionary (js/lyrics/phonedict.js) whose
 * stress is not on the first vowel. A one-off generator, not part of the
 * app; run it again after rebuilding phonedict.js:
 *
 *   node tools/build-stressdict.mjs <cmudict.dict>
 *
 *   cmudict.dict  https://github.com/cmusphinx/cmudict (BSD licence; put its
 *                 LICENSE file next to it)
 *
 * The phones of phonedict.js come from the same entries, so the n-th vowel
 * here is the n-th vowel there.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARPA, isVowelPhone } from '../js/lyrics/phonemes.js';
import { PHONE_DICT } from '../js/lyrics/phonedict.js';

const [dictPath] = process.argv.slice(2);
if (!dictPath) {
  console.error('Usage: node tools/build-stressdict.mjs <cmudict.dict>');
  process.exit(1);
}
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

const cmu = new Map();
for (const line of fs.readFileSync(dictPath, 'utf8').split('\n')) {
  const m = /^([a-z'.-]+)(\(\d+\))?\s+([^#]+)/.exec(line.trim());
  if (!m || m[2]) continue; // first pronunciation only, as phonedict.js
  cmu.set(m[1], m[3].trim().split(/\s+/));
}

const rows = [];
let checked = 0;
for (const line of PHONE_DICT.split('\n')) {
  const sp = line.indexOf(' ');
  if (sp < 0) continue;
  const word = line.slice(0, sp);
  const code = line.slice(sp + 1);
  const arpa = cmu.get(word);
  if (!arpa || [...code].filter(isVowelPhone).length < 2) continue;
  if (arpa.map((p) => ARPA[p.replace(/\d/, '')]).join('') !== code) continue; // not the same entry
  const vowels = arpa.filter((p) => /\d$/.test(p));
  let k = vowels.findIndex((p) => p.endsWith('1'));
  if (k < 0) k = vowels.findIndex((p) => p.endsWith('2'));
  checked += 1;
  if (k > 0) rows.push(`${word} ${k}`);
}

const licencePath = path.join(path.dirname(dictPath), 'LICENSE');
const licence = fs.existsSync(licencePath) ? fs.readFileSync(licencePath, 'utf8').trim() : '';
if (!licence) {
  console.error(`Put CMUdict's LICENSE file next to ${dictPath}: its notice must ship with the data.`);
  process.exit(1);
}
const notice = licence.split(/\r?\n/).map((l) => ` * ${l}`.trimEnd()).join('\n');
const out = `/*
 * Word stress for the robot singer, generated by tools/build-stressdict.mjs
 * from the CMU Pronouncing Dictionary. Do not edit by hand. Each line: a word
 * of phonedict.js and which of its vowels is stressed (0 = the first, 1 = the
 * second...). Words not listed are stressed on their first vowel.
 *
${notice}
 */
export const STRESS_DICT = \`
${rows.join('\n')}
\`;
`;
const dest = path.join(root, 'js', 'lyrics', 'stressdict.js');
fs.writeFileSync(dest, out);
console.log(`${checked} words of two or more vowels, ${rows.length} not stressed on the first: ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB -> ${path.relative(root, dest)}`);
